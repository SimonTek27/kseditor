def translate_ts_file(lang_code, translations):
    ts_file = I18N_DIR / f"kseditor_{lang_code}.ts"
    if not ts_file.exists():
        print(f"File not found: {ts_file}")
        return

    with open(ts_file, "r", encoding="utf-8") as f:
        content = f.read()

    # Parse all <message> blocks
    pattern = re.compile(
        r'<message>\s*<source>([^<]+)</source>\s*<translation[^>]*>([^<]*)</translation>\s*</message>',
        re.DOTALL
    )

    def replace_translation(match):
        source = match.group(1)
        current_trans = match.group(2)
        if source in translations:
            new_trans = translations[source]
            new_trans_escaped = new_trans.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            return f'<message><source>{source}</source><translation>{new_trans_escaped}</translation></message>'
        elif current_trans == source and source != "":
            return match.group(0)  # already identity (en_US)
        return match.group(0)

    new_content = re.sub(
        r'<message>\s*<source>([^<]+)</source>\s*<translation[^>]*>([^<]*)</translation>\s*</message>',
        replace_translation,
        content
    )

    # Now add new messages for sources that exist in our translations but not in the file
    for source, trans in translations.items():
        escaped_source = source.replace("&", "&amp;").replace("'", "&apos;").replace("<", "&lt;").replace(">", "&gt;")
        escaped_trans = trans.replace("&", "&amp;").replace("'", "&apos;").replace("<", "&lt;").replace(">", "&gt;")
        if f"<source>{escaped_source}</source>" not in new_content:
            # Add to an appropriate context - we need to figure out which context
            # For now, we'll add to the MainWindow context as a fallback
            new_content = new_content.replace(
                '</TS>',
                f'  <context>\n    <name>MainWindow</name>\n    <message><source>{escaped_source}</source><translation>{escaped_trans}</translation></message>\n  </context>\n</TS>'
            )

    with open(ts_file, "w", encoding="utf-8") as f:
        f.write(new_content)

    print(f"Updated {ts_file}")

