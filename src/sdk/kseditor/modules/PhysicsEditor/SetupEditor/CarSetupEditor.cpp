QMap<QString, QPair<double, double>> CarSetupEditor::compareSetups(const CarSetup& a, const CarSetup& b) {
    QMap<QString, QPair<double, double>> differences;

    // Brakes
    differences["Brake Bias"] = {a.brakes.frontBrakeBias, b.brakes.frontBrakeBias};
    differences["Brake Pressure"] = {a.brakes.brakePressure, b.brakes.brakePressure};

    // Suspension
    differences["Front Spring Rate"] = {a.suspension.frontSpringRate[0], b.suspension.frontSpringRate[0]};
    differences["Rear Spring Rate"] = {a.suspension.rearSpringRate[0], b.suspension.rearSpringRate[0]};
    differences["Front Ride Height"] = {a.suspension.frontRideHeight, b.suspension.frontRideHeight};
    differences["Rear Ride Height"] = {a.suspension.rearRideHeight, b.suspension.rearRideHeight};
    differences["Front ARB"] = {a.suspension.frontARB, b.suspension.frontARB};
    differences["Rear ARB"] = {a.suspension.rearARB, b.suspension.rearARB};

    // Tyres
    differences["Front Pressure"] = {a.tyres.frontTyrePressure[0], b.tyres.frontTyrePressure[0]};
    differences["Rear Pressure"] = {a.tyres.rearTyrePressure[0], b.tyres.rearTyrePressure[0]};
    differences["Front Camber"] = {a.tyres.frontCamber[0], b.tyres.frontCamber[0]};
    differences["Rear Camber"] = {a.tyres.rearCamber[0], b.tyres.rearCamber[0]};

    // Aero
    differences["Front Wing"] = {a.aero.frontWingAngle, b.aero.frontWingAngle};
    differences["Rear Wing"] = {a.aero.rearWingAngle, b.aero.rearWingAngle};

    // Differential
    differences["Diff Preload"] = {a.differential.preload, b.differential.preload};
    differences["Diff Coast"] = {a.differential.coastPower, b.differential.coastPower};
    differences["Diff Drive"] = {a.differential.drivePower, b.differential.drivePower};

    // Electronics
    differences["TC"] = {a.electronics.tractionControl, b.electronics.tractionControl};
    differences["ABS"] = {a.electronics.abs, b.electronics.abs};

    // Engine
    differences["Fuel Load"] = {a.engine.fuelLoad, b.engine.fuelLoad};

    return differences;
}

