    stream << "FRONT_POWER_R=" << QString::number(setup.brakes.frontBrakePower[1], 'f', 4) << "\n";
    stream << "REAR_POWER_L=" << QString::number(setup.brakes.rearBrakePower[0], 'f', 4) << "\n";
    stream << "REAR_POWER_R=" << QString::number(setup.brakes.rearBrakePower[1], 'f', 4) << "\n\n";

