    stream << "FRONT_SPRING_L=" << QString::number(setup.suspension.frontSpringRate[0], 'f', 2) << "\n";
    stream << "FRONT_SPRING_R=" << QString::number(setup.suspension.frontSpringRate[1], 'f', 2) << "\n";
    stream << "REAR_SPRING_L=" << QString::number(setup.suspension.rearSpringRate[0], 'f', 2) << "\n";
