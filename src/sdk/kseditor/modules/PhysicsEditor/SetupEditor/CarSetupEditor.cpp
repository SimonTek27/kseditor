bool CarSetupEditor::validateSetup(const CarSetup& setup, QString* error) {
    // Brake validation
    if (setup.brakes.frontBrakeBias < 30.0f || setup.brakes.frontBrakeBias > 70.0f) {
        if (error) *error = "Brake bias out of range (30-70%)";
        return false;
    }

    if (setup.brakes.brakePressure < 50.0f || setup.brakes.brakePressure > 150.0f) {
        if (error) *error = "Brake pressure out of range (50-150%)";
        return false;
    }

    // Suspension validation
    if (setup.suspension.frontRideHeight < 20.0f || setup.suspension.frontRideHeight > 100.0f) {
        if (error) *error = "Front ride height out of range (20-100mm)";
        return false;
    }

    if (setup.suspension.rearRideHeight < 20.0f || setup.suspension.rearRideHeight > 100.0f) {
        if (error) *error = "Rear ride height out of range (20-100mm)";
        return false;
    }

    // Tyre validation
    for (int i = 0; i < 2; ++i) {
        if (setup.tyres.frontTyrePressure[i] < 15.0f || setup.tyres.frontTyrePressure[i] > 50.0f) {
            if (error) *error = "Front tyre pressure out of range (15-50 PSI)";
            return false;
        }

        if (setup.tyres.rearTyrePressure[i] < 15.0f || setup.tyres.rearTyrePressure[i] > 50.0f) {
            if (error) *error = "Rear tyre pressure out of range (15-50 PSI)";
            return false;
        }
    }

    // Aero validation
    if (setup.aero.frontWingAngle < 0.0f || setup.aero.frontWingAngle > 20.0f) {
        if (error) *error = "Front wing angle out of range (0-20 degrees)";
        return false;
    }

    if (setup.aero.rearWingAngle < 0.0f || setup.aero.rearWingAngle > 20.0f) {
        if (error) *error = "Rear wing angle out of range (0-20 degrees)";
        return false;
    }

    // Differential validation
    if (setup.differential.preload < 0.0f || setup.differential.preload > 100.0f) {
        if (error) *error = "Differential preload out of range (0-100 Nm)";
        return false;
    }

    // Electronics validation
    if (setup.electronics.tractionControl < 0.0f || setup.electronics.tractionControl > 10.0f) {
        if (error) *error = "TC out of range (0-10)";
        return false;
    }

    if (setup.electronics.abs < 0.0f || setup.electronics.abs > 10.0f) {
        if (error) *error = "ABS out of range (0-10)";
        return false;
    }

    // Engine validation
    if (setup.engine.fuelLoad < 0.0f || setup.engine.fuelLoad > setup.engine.fuelCapacity) {
        if (error) *error = "Fuel load exceeds capacity";
        return false;
    }

    return true;
}

