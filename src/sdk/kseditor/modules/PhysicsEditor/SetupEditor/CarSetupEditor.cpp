QStringList CarSetupEditor::getAvailableSetups(const QString& carPath) {
    QStringList setups;

    QString setupsDir = carPath + "/setup";
    QDir dir(setupsDir);
    if (dir.exists()) {
        QFileInfoList files = dir.entryInfoList(QStringList() << "*.ini", QDir::Files);
        for (const QFileInfo& fileInfo : files) {
            setups.append(fileInfo.baseName());
        }
    }

    return setups;
}

CarSetupEditor::CarSetup CarSetupEditor::getSetup(const QString& carPath, const QString& setupName) {
    QString setupPath = carPath + "/setup/" + setupName + ".ini";
    return loadSetup(setupPath);
}

bool CarSetupEditor::deleteSetup(const QString& carPath, const QString& setupName) {
    QString setupPath = carPath + "/setup/" + setupName + ".ini";
    return QFile::remove(setupPath);
}

bool CarSetupEditor::copySetup(const QString& carPath, const QString& sourceName, const QString& destName) {
    QString sourcePath = carPath + "/setup/" + sourceName + ".ini";
    QString destPath = carPath + "/setup/" + destName + ".ini";
    return QFile::copy(sourcePath, destPath);
}

