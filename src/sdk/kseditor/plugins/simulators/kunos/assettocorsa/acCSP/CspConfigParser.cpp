QVariantMap CspConfigParser::parseIniFile(const QString& path) {
    QVariantMap root;
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text))
        return root;

    QTextStream in(&file);
    QString currentSection;
    static QRegularExpression sectionRe(R"(\[([^\]]+)\])");
    static QRegularExpression commentRe(R"(^(;|#).*)");

    while (!in.atEnd()) {
        QString line = in.readLine();

        if (commentRe.match(line).hasMatch())
            continue;

        QRegularExpressionMatch sectionMatch = sectionRe.match(line);
        if (sectionMatch.hasMatch()) {
            currentSection = sectionMatch.captured(1).trimmed();
            if (!root.contains(currentSection))
                root[currentSection] = QVariantMap();
            continue;
        }

        int eq = line.indexOf('=');
        if (eq > 0) {
            QString key = line.left(eq).trimmed();
            QString val = line.mid(eq + 1).trimmed();
            if (val.startsWith('"') && val.endsWith('"'))
                val = val.mid(1, val.size() - 2);
            if (!key.isEmpty()) {
                if (!currentSection.isEmpty()) {
                    QVariantMap section = root[currentSection].toMap();
                    section[key] = val;
                    root[currentSection] = section;
                }
            }
        }
    }

    file.close();
    return root;
}

bool CspConfigParser::writeIniFile(const QString& path, const QVariantMap& sections) {
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text))
        return false;

    QTextStream out(&file);
    out << "; Generated by ksEditor CSP Config Editor\n\n";

    for (auto sectionIt = sections.constBegin(); sectionIt != sections.constEnd(); ++sectionIt) {
        out << "[" << sectionIt.key() << "]\n";
        const QVariant sectionVal = sectionIt.value();
        if (sectionVal.typeId() == QVariant::Map) {
            QVariantMap keys = sectionVal.toMap();
            for (auto keyIt = keys.constBegin(); keyIt != keys.constEnd(); ++keyIt) {
                out << keyIt.key() << "=" << keyIt.value().toString() << "\n";
            }
        }
        out << "\n";
    }

    file.close();
    return true;
}

QVariantMap CspConfigParser::loadCarConfig(const QString& path) {
    return parseIniFile(path);
}

QVariantMap CspConfigParser::loadTrackConfig(const QString& path) {
    return parseIniFile(path);
}

bool CspConfigParser::saveCarConfig(const QString& path, const QVariantMap& data) {
    QDir().mkpath(QFileInfo(path).absolutePath());
    return writeIniFile(path, data);
}

bool CspConfigParser::saveTrackConfig(const QString& path, const QVariantMap& data) {
    QDir().mkpath(QFileInfo(path).absolutePath());
    return writeIniFile(path, data);
}

QVariantList CspConfigParser::parseEmissives(const QVariantMap& sections) {
    QVariantList result;

    for (auto it = sections.constBegin(); it != sections.constEnd(); ++it) {
        const QString& sectionName = it.key();
        if (sectionName.startsWith("EMISSIVE") || sectionName.startsWith("EMISSIVE_LIGHT")) {
            QVariantMap section = it.value().toMap();

            CspEmissiveConfig config;
            config.name = section.value("NAME").toString();
            config.meshName = section.value("MESHES").toString();
            config.materialName = section.value("MATERIALS").toString();
            config.color = section.value("COLOR").toString();
            config.colorOff = section.value("OFF_COLOR").toString();
            config.location = section.value("LOCATION").toString();
            config.lag = section.value("LAG", 0.0).toDouble();
            config.simulateHeating = section.value("SIMULATE_HEATING", 0.0).toDouble();
            config.bindToHeadlights = section.value("BIND_TO_HEADLIGHTS", "0").toString() == "1";
            config.active = section.value("ACTIVE", "1").toString() == "1";
            config.condition = section.value("CONDITION").toString();

            QVariantMap map;
            map.insert("name", config.name);
            map.insert("meshName", config.meshName);
            map.insert("color", config.color);
            map.insert("colorOff", config.colorOff);
            map.insert("location", config.location);
            map.insert("lag", config.lag);
            map.insert("simulateHeating", config.simulateHeating);
            map.insert("bindToHeadlights", config.bindToHeadlights);
            map.insert("active", config.active);
            map.insert("condition", config.condition);
            map.insert("sectionName", sectionName);
            result.append(map);
        }
    }
    return result;
}

