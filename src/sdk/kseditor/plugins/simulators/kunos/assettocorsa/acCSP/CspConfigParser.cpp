QString CspConfigParser::colorToString(const QVariantMap& colorMap)
{
    int r = colorMap.value("r", 255).toInt();
    int g = colorMap.value("g", 255).toInt();
    int b = colorMap.value("b", 255).toInt();
    int a = colorMap.value("a", 255).toInt();
    return QString("rgba(%1, %2, %3, %4)").arg(r).arg(g).arg(b).arg(a);
}

QVariantMap CspConfigParser::stringToColor(const QString& colorStr)
{
    QVariantMap result;
    result["r"] = 255;
    result["g"] = 255;
    result["b"] = 255;
    result["a"] = 255;

    QRegularExpression re(R"(rgba?\s*\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*(\d+))?\s*\))");
    QRegularExpressionMatch m = re.match(colorStr.trimmed());
    if (m.hasMatch()) {
        result["r"] = m.captured(1).toInt();
        result["g"] = m.captured(2).toInt();
        result["b"] = m.captured(3).toInt();
        result["a"] = m.captured(4).isEmpty() ? 255 : m.captured(4).toInt();
    } else if (colorStr.startsWith("#")) {
        QColor c(colorStr);
        if (c.isValid()) {
            result["r"] = c.red();
            result["g"] = c.green();
            result["b"] = c.blue();
            result["a"] = c.alpha();
        }
    }
    return result;
}

QString CspConfigParser::positionToString(const QVariantMap& posMap)
{
    double x = posMap.value("x", 0.0).toDouble();
    double y = posMap.value("y", 0.0).toDouble();
    double z = posMap.value("z", 0.0).toDouble();
    return QString("%1,%2,%3").arg(x, 0, 'f', 4).arg(y, 0, 'f', 4).arg(z, 0, 'f', 4);
}

QVariantMap CspConfigParser::stringToPosition(const QString& posStr)
{
    QVariantMap result;
    result["x"] = 0.0;
    result["y"] = 0.0;
    result["z"] = 0.0;

    QStringList parts = posStr.split(',', Qt::SkipEmptyParts);
    if (parts.size() >= 3) {
        result["x"] = parts[0].trimmed().toDouble();
        result["y"] = parts[1].trimmed().toDouble();
        result["z"] = parts[2].trimmed().toDouble();
    }
    return result;
}

