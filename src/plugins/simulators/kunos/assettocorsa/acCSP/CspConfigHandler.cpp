    if (upperType == "LIGHT")
        return (name.startsWith("LIGHT_") && !name.startsWith("LIGHT_SERIES") &&
                name != "LIGHTING" && name != "LIGHT_POLLUTION");
    if (upperType == "SHADER_REPLACEMENT")
        return name.startsWith("SHADER_REPLACEMENT_") || name.startsWith("SHADER_REPLACEMENT...");
