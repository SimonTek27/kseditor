// ── Parse: Material Adjustments ──────────────────────────────────────────────

QVariantList CspConfigHandler::parseMaterialAdjustments(const QVariantMap& sections) {
    QVariantList result;
    for (auto it = sections.constBegin(); it != sections.constEnd(); ++it) {
        if (!isSectionType(it.key(), "MATERIAL_ADJUSTMENT")) continue;
        QVariantMap section = it.value().toMap();
        QVariantMap adj;
        adj["sectionName"] = it.key();
        adj["active"] = section.value("ACTIVE", "1").toString() == "1";
        adj["description"] = section.value("DESCRIPTION").toString();
        adj["meshName"] = section.value("MESHES").toString();
        adj["materialName"] = section.value("MATERIALS").toString();
        adj["condition"] = section.value("CONDITION").toString();
        adj["visibilityLevel"] = section.value("VISIBILITY_LEVEL", "0").toInt();
        adj["blendMode"] = section.value("BLEND_MODE").toString();
        adj["range"] = section.value("RANGE", "20").toDouble();
        adj["rangeGradientOffset"] = section.value("RANGE_GRADIENT_OFFSET", "0.2").toDouble();
        adj["spot"] = section.value("SPOT", "75").toDouble();
        adj["spotSharpness"] = section.value("SPOT_SHARPNESS", "0.5").toDouble();

        QVariantList keyValues;
        for (int k = 0; k < 10; ++k) {
            QString keyKey = QString("KEY_%1").arg(k);
            QString valKey = QString("VALUE_%1").arg(k);
            QString offKey = QString("VALUE_%1_OFF").arg(k);
            QString offValKey = QString("OFF_VALUE_%1").arg(k);
            if (section.contains(keyKey) || section.contains(valKey)) {
                QVariantMap kv;
                kv["key"] = section.value(keyKey).toString();
                kv["value"] = section.value(valKey).toString();
                kv["off"] = section.contains(offKey) ? section.value(offKey).toString() : section.value(offValKey).toString();
                keyValues.append(kv);
            }
        }
        adj["keyValues"] = keyValues;
        result.append(adj);
    }
    return result;
}

