// ── INI Parsing ──────────────────────────────────────────────────────────────

QVariantMap CspConfigHandler::parseIniFile(const QString& path) {
    QVariantMap root;
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text))
        return root;

    QTextStream in(&file);
    in.setEncoding(QStringConverter::Utf8);
    QString currentSection;
    static QRegularExpression sectionRe(R"(\[([^\]]+)\])");
    static QRegularExpression commentRe(R"(^(;|#).*)");

    while (!in.atEnd()) {
        QString line = in.readLine().trimmed();

        if (line.isEmpty() || commentRe.match(line).hasMatch())
            continue;

        QRegularExpressionMatch sectionMatch = sectionRe.match(line);
        if (sectionMatch.hasMatch()) {
            currentSection = sectionMatch.captured(1).trimmed();
            if (!root.contains(currentSection))
                root[currentSection] = QVariantMap();
            continue;
        }

        int eq = line.indexOf('=');
        if (eq > 0 && !currentSection.isEmpty()) {
            QString key = line.left(eq).trimmed();
            QString val = line.mid(eq + 1).trimmed();
            if (val.startsWith('"') && val.endsWith('"'))
                val = val.mid(1, val.size() - 2);
            if (!key.isEmpty()) {
                QVariantMap section = root[currentSection].toMap();
                section[key] = val;
                root[currentSection] = section;
            }
        }
    }

    file.close();
    return root;
}

bool CspConfigHandler::writeIniFile(const QString& path, const QVariantMap& sections) {
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text))
        return false;

    QTextStream out(&file);
    out.setEncoding(QStringConverter::Utf8);
    out << "; Generated by ksEditor CSP Config Editor\n\n";

    for (auto it = sections.constBegin(); it != sections.constEnd(); ++it) {
        out << "[" << it.key() << "]\n";
        const QVariant sectionVal = it.value();
        if (sectionVal.typeId() == QVariant::Map) {
            QVariantMap keys = sectionVal.toMap();
            for (auto keyIt = keys.constBegin(); keyIt != keys.constEnd(); ++keyIt) {
                out << keyIt.key() << "=" << keyIt.value().toString() << "\n";
            }
        }
        out << "\n";
    }

    file.close();
    return true;
}

// ── Load / Save ──────────────────────────────────────────────────────────────

QVariantMap CspConfigHandler::loadConfig(const QString& path) {
    return parseIniFile(path);
}

bool CspConfigHandler::saveConfig(const QString& path, const QVariantMap& sections) {
    QDir().mkpath(QFileInfo(path).absolutePath());
    return writeIniFile(path, sections);
}

QVariantMap CspConfigHandler::loadWithIncludes(const QString& path) {
    QVariantMap config = parseIniFile(path);
    QString basePath = QFileInfo(path).absolutePath();

    QStringList includeKeys;
    for (auto it = config.constBegin(); it != config.constEnd(); ++it) {
        if (it.key().startsWith("INCLUDE")) {
            includeKeys.append(it.key());
        }
    }

    QVariantMap merged;
    for (const QString& key : includeKeys) {
        QVariantMap section = config.value(key).toMap();
        QString includePath = section.value("INCLUDE").toString();
        if (!includePath.isEmpty()) {
            QString resolvedPath = resolveIncludePath(basePath, includePath);
            if (QFileInfo::exists(resolvedPath)) {
                QVariantMap included = parseIniFile(resolvedPath);
                merged = mergeConfigs(merged, included);
            }
        }
    }

    merged = mergeConfigs(merged, config);
    return merged;
}

QVariantMap CspConfigHandler::mergeConfigs(const QVariantMap& base, const QVariantMap& overlay) {
    QVariantMap result = base;
    for (auto it = overlay.constBegin(); it != overlay.constEnd(); ++it) {
        if (it.key().startsWith("INCLUDE")) continue;
        if (result.contains(it.key())) {
            QVariantMap baseSection = result[it.key()].toMap();
            QVariantMap overlaySection = it.value().toMap();
            for (auto kIt = overlaySection.constBegin(); kIt != overlaySection.constEnd(); ++kIt) {
                baseSection[kIt.key()] = kIt.value();
            }
            result[it.key()] = baseSection;
        } else {
            result[it.key()] = it.value();
        }
    }
    return result;
}

QString CspConfigHandler::resolveIncludePath(const QString& basePath, const QString& includePath) {
    if (QFileInfo(includePath).isAbsolute())
        return includePath;
    return QDir(basePath).absoluteFilePath(includePath);
}

