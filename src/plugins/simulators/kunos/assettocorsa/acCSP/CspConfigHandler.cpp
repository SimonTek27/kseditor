// ── Shader compilation ──────────────────────────────────────────────────────

QVariantMap CspConfigHandler::compileShader(const QString& source, bool isFragment,
                                             const QString& entryPoint) {
    ShaderCompileResult result = CspShaderCompiler::compileGLSL(source, isFragment, entryPoint);
    QVariantMap map;
    map["success"] = result.success;
    map["spirvSize"] = result.spirv.size();
    map["compiler"] = result.compilerUsed;
    map["errors"] = QVariant::fromValue(result.errors);
    return map;
}

QVariantMap CspConfigHandler::profileShader(const QString& source) {
    ShaderProfile profile = CspShaderCompiler::profileShader(source);
    QVariantMap map;
    map["estimatedInstructions"] = profile.estimatedInstructions;
    map["textureSamples"] = profile.textureSamples;
    map["uniformCount"] = profile.uniformCount;
    map["inputCount"] = profile.inputCount;
    map["outputCount"] = profile.outputCount;
    map["branchCount"] = profile.branchCount;
    map["loopCount"] = profile.loopCount;
    map["functionCalls"] = profile.functionCalls;
    map["usesDiscard"] = profile.usesDiscard;
    map["usesDerivatives"] = profile.usesDerivatives;
    map["estimatedComplexity"] = profile.estimatedComplexity;
    map["summary"] = profile.summary();
    emit shaderProfileReady(profile.name, map);
    return map;
}

QStringList CspConfigHandler::compileShaderReplacement(const QVariantMap& sections,
                                                         const QString& sectionName) {
    QStringList errors;
    if (!sections.contains(sectionName)) {
        errors << "Section not found: " + sectionName;
        return errors;
    }

    QVariantMap section = sections[sectionName].toMap();
    QString source;
    if (section.contains("SOURCE")) {
        source = section["SOURCE"].toString();
    } else if (section.contains("FILE")) {
        QFile f(section["FILE"].toString());
        if (f.open(QIODevice::ReadOnly | QIODevice::Text))
            source = QString::fromUtf8(f.readAll());
    }

    if (source.isEmpty()) {
        errors << "No shader source found in " + sectionName;
        return errors;
    }

    bool isFragment = sectionName.contains("PS", Qt::CaseInsensitive) ||
                      sectionName.contains("PIXEL", Qt::CaseInsensitive) ||
                      sectionName.contains("FRAG", Qt::CaseInsensitive);

    ShaderCompileResult result = CspShaderCompiler::compileGLSL(source, isFragment);
    if (!result.success) {
        errors = result.errors;
    }

    emit shaderCompiled(sectionName, result.success);
    return errors;
}

QVariantList CspConfigHandler::profileShaderReplacements(const QVariantMap& sections) {
    QVariantList profiles;
    QStringList shaderSections = findSectionsByType(sections, "SHADER_REPLACEMENT");

    for (const QString& name : shaderSections) {
        QVariantMap section = sections[name].toMap();
        QString source = section.value("SOURCE", section.value("FILE", "")).toString();

        if (!source.isEmpty()) {
            ShaderProfile profile = CspShaderCompiler::profileShader(source);
            QVariantMap p;
            p["name"] = name;
            p["estimatedInstructions"] = profile.estimatedInstructions;
            p["textureSamples"] = profile.textureSamples;
            p["estimatedComplexity"] = profile.estimatedComplexity;
            p["summary"] = profile.summary();
            profiles.append(p);
        }
    }
    return profiles;
}

bool CspConfigHandler::saveCompiledShader(const QVariantMap& sections, const QString& sectionName, const QString& outputDir) {
    if (!sections.contains(sectionName)) return false;

    QVariantMap section = sections[sectionName].toMap();
    QString source = section.value("SOURCE", section.value("FILE", "")).toString();
    if (source.isEmpty()) return false;

    bool isFragment = sectionName.contains("PS", Qt::CaseInsensitive) ||
                      sectionName.contains("PIXEL", Qt::CaseInsensitive) ||
                      sectionName.contains("FRAG", Qt::CaseInsensitive);

    ShaderCompileResult result = CspShaderCompiler::compileGLSL(source, isFragment);
    if (!result.success) return false;

    QDir dir(outputDir);
    if (!dir.exists()) dir.mkpath(".");
    QString outPath = dir.filePath(sectionName + ".spv");
    QFile f(outPath);
    if (!f.open(QIODevice::WriteOnly)) return false;
    f.write(result.spirv);
    f.close();
    return true;
}

