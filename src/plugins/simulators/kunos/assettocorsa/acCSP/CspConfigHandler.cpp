QStringList CspConfigHandler::findSectionsByType(const QVariantMap& sections, const QString& type) {
    QStringList result;
    for (auto it = sections.constBegin(); it != sections.constEnd(); ++it) {
        if (isSectionType(it.key(), type))
            result.append(it.key());
    }
    return result;
}

QVariantList CspConfigHandler::getSectionProperties(const QVariantMap& sections, const QString& sectionName) {
    QVariantList result;
    if (!sections.contains(sectionName)) return result;
    QVariantMap section = sections[sectionName].toMap();
    for (auto it = section.constBegin(); it != section.constEnd(); ++it) {
        QVariantMap prop;
        prop["key"] = it.key();
        prop["value"] = it.value();
        result.append(prop);
    }
    return result;
}

