QString CspConfigHandler::generateSectionName(const QString& type, const QVariantMap& existingSections) {
    int idx = findNextIndex(existingSections, type);
    return QString("%1_%2").arg(type).arg(idx);
}

int CspConfigHandler::findNextIndex(const QVariantMap& sections, const QString& type) {
    int maxIdx = -1;
    for (auto it = sections.constBegin(); it != sections.constEnd(); ++it) {
        if (isSectionType(it.key(), type)) {
            QRegularExpression re(QString(R"((\d+)\.\.\.|\b(\d+)$)"));
            QRegularExpressionMatch m = re.match(it.key());
            if (m.hasMatch()) {
                if (!m.captured(1).isEmpty()) {
                    return -1;
                }
                int idx = m.captured(2).toInt();
                if (idx > maxIdx) maxIdx = idx;
            }
        }
    }
    return maxIdx + 1;
}

QStringList CspConfigHandler::extractList(const QString& str) {
    QStringList result;
    if (str.isEmpty()) return result;
    for (const QString& s : str.split(',', Qt::SkipEmptyParts)) {
        result.append(s.trimmed());
    }
    return result;
}

QString CspConfigHandler::joinList(const QStringList& list) {
    return list.join(", ");
}

