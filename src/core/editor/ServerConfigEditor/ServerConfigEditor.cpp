bool ServerConfigEditor::parseEntryLine(const QString& line, EntryInfo& entry) {
    if (!line.contains('=')) return false;

    int eqPos = line.indexOf('=');
    QString key = line.left(eqPos).trimmed();
    QString value = line.mid(eqPos + 1).trimmed();

    if (key == "DRIVERNAME") entry.name = value;
    else if (key == "TEAM") entry.team = value;
    else if (key == "GUID") entry.guid = value;
    else if (key == "MODEL") entry.carModel = value;
    else if (key == "SKIN") entry.skin = value;
    else if (key == "SPECTATOR_MODE") entry.spectatorMode = value.toInt();
    else if (key == "BALLAST") entry.ballast = value.toInt();
    else if (key == "RESTRICTOR") entry.restrictor = value.toInt();
    else return false;

    return true;
}

QString ServerConfigEditor::formatEntryLine(const EntryInfo& entry) {
    QString result;
    result += "DRIVERNAME=" + entry.name + "\n";
    result += "TEAM=" + entry.team + "\n";
    result += "GUID=" + entry.guid + "\n";
    result += "MODEL=" + entry.carModel + "\n";
    result += "SKIN=" + entry.skin + "\n";
    result += "SPECTATOR_MODE=" + QString::number(entry.spectatorMode) + "\n";
    result += "BALLAST=" + QString::number(entry.ballast) + "\n";
    result += "RESTRICTOR=" + QString::number(entry.restrictor);
    return result;
}
