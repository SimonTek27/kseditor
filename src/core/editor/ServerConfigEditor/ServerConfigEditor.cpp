// ============================================================================

bool ServerConfigEditor::validateConfig(const ServerConfig& config, QString* error) {
    if (config.name.isEmpty()) {
        if (error) *error = "Server name is empty";
        return false;
    }

    if (config.port < 1024 || config.port > 65535) {
        if (error) *error = "Invalid port number";
        return false;
    }

    if (config.maxClients < 1 || config.maxClients > 100) {
        if (error) *error = "Invalid max clients (1-100)";
        return false;
    }

    if (config.sessionDuration < 60) {
        if (error) *error = "Session duration too short (minimum 60 seconds)";
        return false;
    }

    return true;
}

bool ServerConfigEditor::validateEntryList(const QVector<EntryInfo>& entries, QString* error) {
    QStringList guids;

    for (const EntryInfo& entry : entries) {
        if (entry.guid.isEmpty()) {
            if (error) *error = "Entry missing GUID";
            return false;
        }

        if (entry.carModel.isEmpty()) {
            if (error) *error = "Entry missing car model: " + entry.name;
            return false;
        }

        if (guids.contains(entry.guid)) {
            if (error) *error = "Duplicate GUID: " + entry.guid;
            return false;
        }

        guids.append(entry.guid);
    }

    return true;
}

