bool ServerConfigEditor::loadExtraConfig(ServerConfig& config, const QString& serverPath) {
    QString extraPath = serverPath + "/cfg/extra_cfg.yml";
    QFile file(extraPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        return false;
    }

    QTextStream stream(&file);
    QString content = stream.readAll();
    file.close();

    // Parse YAML-like format
    QRegularExpression kvRegex("^(\\w[\\w\\s]*):\\s*(.+)$");
    QStringList lines = content.split('\n');

    for (const QString& line : lines) {
        QString trimmed = line.trimmed();
        if (trimmed.startsWith('#')) continue;

        QRegularExpressionMatch match = kvRegex.match(trimmed);
        if (match.hasMatch()) {
            QString key = match.captured(1).trimmed();
            QString value = match.captured(2).trimmed();

            config.cspSettings[key] = value;

            if (key == "ENABLE_CSP") {
                config.enableCsp = (value == "1" || value.toLower() == "true");
            } else if (key == "CSP_VERSION") {
                config.cspVersion = value;
            }
        }
    }

    return true;
}

bool ServerConfigEditor::saveExtraConfig(const ServerConfig& config, const QString& serverPath) {
    QString extraPath = serverPath + "/cfg/extra_cfg.yml";
    QFile file(extraPath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        return false;
    }

    QTextStream stream(&file);
    stream << "# CSP Extra Configuration\n";
    stream << "# Generated by ksEditor\n\n";

    stream << "ENABLE_CSP: " << (config.enableCsp ? "1" : "0") << "\n";

    if (!config.cspVersion.isEmpty()) {
        stream << "CSP_VERSION: " << config.cspVersion << "\n";
    }

    // Write other CSP settings
    for (auto it = config.cspSettings.begin(); it != config.cspSettings.end(); ++it) {
        if (it.key() != "ENABLE_CSP" && it.key() != "CSP_VERSION") {
            stream << it.key() << ": " << it.value() << "\n";
        }
    }

    file.close();
    return true;
}

