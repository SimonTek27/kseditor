QString ServerConfigEditor::getSessionTypeName(int type) {
    switch (type) {
        case 0: return "Practice";
        case 1: return "Qualifying";
        case 2: return "Race";
        default: return "Unknown";
    }
}

QString ServerConfigEditor::getWeatherName(const QString& weatherId) {
    static QMap<QString, QString> weatherNames;
    if (weatherNames.isEmpty()) {
        weatherNames["clear_01"] = "Clear";
        weatherNames["cloudy_01"] = "Cloudy";
        weatherNames["light_rain_01"] = "Light Rain";
        weatherNames["heavy_rain_01"] = "Heavy Rain";
        weatherNames["storm_01"] = "Storm";
        weatherNames["fog_01"] = "Fog";
    }
    return weatherNames.value(weatherId, weatherId);
}

QStringList ServerConfigEditor::getAvailableTracks(const QString& contentPath) {
    QStringList tracks;

    QDir tracksDir(contentPath + "/tracks");
    if (tracksDir.exists()) {
        QFileInfoList dirs = tracksDir.entryInfoList(QDir::Dirs | QDir::NoDotAndDotDot);
        for (const QFileInfo& dirInfo : dirs) {
            tracks.append(dirInfo.fileName());
        }
    }

    return tracks;
}

