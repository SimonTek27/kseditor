QVector<ServerConfigEditor::EntryInfo> ServerConfigEditor::loadEntryList(const QString& serverPath) {
    QVector<EntryInfo> entries;

    QString entryPath = serverPath + "/cfg/entry_list.ini";
    QFile file(entryPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        return entries;
    }

    QTextStream stream(&file);
    EntryInfo currentEntry;
    bool inEntry = false;

    while (!stream.atEnd()) {
        QString line = stream.readLine().trimmed();

        // Skip comments and empty lines
        if (line.startsWith(';') || line.startsWith('#') || line.isEmpty()) {
            continue;
        }

        // Section header
        if (line.startsWith('[') && line.endsWith(']')) {
            // Save previous entry
            if (inEntry && !currentEntry.guid.isEmpty()) {
                entries.append(currentEntry);
            }

            QString section = line.mid(1, line.length() - 2);
            inEntry = section.startsWith("CAR_");

            if (inEntry) {
                currentEntry = EntryInfo();
            }
            continue;
        }

        // Key-value pair
        if (inEntry && line.contains('=')) {
            int eqPos = line.indexOf('=');
            QString key = line.left(eqPos).trimmed();
            QString value = line.mid(eqPos + 1).trimmed();

            if (key == "DRIVERNAME") currentEntry.name = value;
            else if (key == "TEAM") currentEntry.team = value;
            else if (key == "GUID") currentEntry.guid = value;
            else if (key == "MODEL") currentEntry.carModel = value;
            else if (key == "SKIN") currentEntry.skin = value;
            else if (key == "SPECTATOR_MODE") currentEntry.spectatorMode = value.toInt();
            else if (key == "BALLAST") currentEntry.ballast = value.toInt();
            else if (key == "RESTRICTOR") currentEntry.restrictor = value.toInt();
        }
    }

    // Save last entry
    if (inEntry && !currentEntry.guid.isEmpty()) {
        entries.append(currentEntry);
    }

    file.close();
    return entries;
}

bool ServerConfigEditor::saveEntryList(const QVector<EntryInfo>& entries, const QString& serverPath) {
    QString entryPath = serverPath + "/cfg/entry_list.ini";
    QFile file(entryPath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        return false;
    }

    QTextStream stream(&file);
    stream << EditorConfig::instance().serverEntryListHeader();
    stream << "; Generated by ksEditor\n\n";

    for (int i = 0; i < entries.size(); ++i) {
        stream << "[CAR_" << i << "]\n";
        stream << formatEntryLine(entries[i]) << "\n\n";
    }

    file.close();
    return true;
}

bool ServerConfigEditor::addEntry(const EntryInfo& entry, const QString& serverPath) {
    QVector<EntryInfo> entries = loadEntryList(serverPath);
    entries.append(entry);
    return saveEntryList(entries, serverPath);
}

bool ServerConfigEditor::removeEntry(const QString& guid, const QString& serverPath) {
    QVector<EntryInfo> entries = loadEntryList(serverPath);

    for (int i = entries.size() - 1; i >= 0; --i) {
        if (entries[i].guid == guid) {
            entries.remove(i);
        }
    }

    return saveEntryList(entries, serverPath);
}

bool ServerConfigEditor::updateEntry(const EntryInfo& entry, const QString& serverPath) {
    QVector<EntryInfo> entries = loadEntryList(serverPath);

    for (int i = 0; i < entries.size(); ++i) {
        if (entries[i].guid == entry.guid) {
            entries[i] = entry;
            return saveEntryList(entries, serverPath);
        }
    }

    return false;
}

