ServerConfigEditor::ServerConfig ServerConfigEditor::loadConfig(const QString& serverPath) {
    ServerConfig config;

    // Load main config
    QString iniPath = serverPath + "/cfg/server_cfg.ini";
    if (QFile::exists(iniPath)) {
        loadFromIni(config, iniPath);
    }

    // Load extra/CSP config
    QString extraPath = serverPath + "/cfg/extra_cfg.yml";
    if (QFile::exists(extraPath)) {
        loadExtraConfig(config, serverPath);
    }

    return config;
}

bool ServerConfigEditor::saveConfig(const ServerConfig& config, const QString& serverPath) {
    // Save main config
    QString iniPath = serverPath + "/cfg/server_cfg.ini";
    if (!saveToIni(config, iniPath)) {
        return false;
    }

    // Save extra/CSP config if enabled
    if (config.enableCsp) {
        saveExtraConfig(config, serverPath);
    }

    return true;
}

bool ServerConfigEditor::loadFromIni(ServerConfig& config, const QString& iniPath) {
    QFile file(iniPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        return false;
    }

    QTextStream stream(&file);
    QString currentSection;

    while (!stream.atEnd()) {
        QString line = stream.readLine().trimmed();

        // Skip comments and empty lines
        if (line.startsWith(';') || line.startsWith('#') || line.isEmpty()) {
            continue;
        }

        // Section header
        if (line.startsWith('[') && line.endsWith(']')) {
            currentSection = line.mid(1, line.length() - 2);
            continue;
        }

        // Key-value pair
        if (line.contains('=')) {
            int eqPos = line.indexOf('=');
            QString key = line.left(eqPos).trimmed();
            QString value = line.mid(eqPos + 1).trimmed();

            // Parse based on key name
            if (key == "NAME") config.name = value;
            else if (key == "DESCRIPTION") config.description = value;
            else if (key == "PASSWORD") config.password = value;
            else if (key == "ADMIN_PASSWORD") config.adminPassword = value;
            else if (key == "IP") config.ip = value;
            else if (key == "PORT") config.port = value.toInt();
            else if (key == "HTTP_PORT") config.httpPort = value.toInt();
            else if (key == "MAX_CLIENTS") config.maxClients = value.toInt();
            else if (key == "SLOT_COUNT") config.slotCount = value.toInt();
            else if (key == "TRACK") config.track = value.toInt();
            else if (key == "CONFIG_TRACK") config.trackConfig = value;
            else if (key == "SESSION_TYPE") config.sessionType = value.toInt();
            else if (key == "SESSION_DURATION") config.sessionDuration = value.toInt();
            else if (key == "LAPS_COUNT") config.lapsCount = value.toInt();
            else if (key == "WAIT_TIME") config.waitTime = value.toInt();
            else if (key == "WEATHER") config.weather = value;
            else if (key == "TIME_OF_DAY") config.timeOfDay = value.toFloat();
            else if (key == "SUN_ANGLE") config.sunAngle = value.toFloat();
            else if (key == "USE_REAL_WEATHER") config.useRealWeather = (value == "1");
            else if (key == "TIME_MULTIPLIER") config.timeMultiplier = value.toInt();
            else if (key == "GRIP") config.gripModifier = value.toFloat();
            else if (key == "DYNAMIC_TRACK") config.dynamicTrack = (value == "1");
            else if (key == "TRACK_CONDITIONS") config.trackConditions = value.toInt();
            else if (key == "IS_LOCKED") config.isLocked = (value == "1");
            else if (key == "ALLOW_AUTOPILOT") config.allowAutopilot = (value == "1");
            else if (key == "ALLOW_VIRTUAL_MIRROR") config.allowVirtualMirror = (value == "1");
            else if (key == "MAX_BALLAST") config.maxBallast = value.toInt();
            else if (key == "DUMP_INTERVAL") config.dumpInterval = value.toInt();
        }
    }

    file.close();
    return true;
}

bool ServerConfigEditor::saveToIni(const ServerConfig& config, const QString& iniPath) {
    QFile file(iniPath);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        return false;
    }

    QTextStream stream(&file);
    stream << EditorConfig::instance().serverConfigHeader();
    stream << "; Generated by ksEditor\n\n";

    stream << "[SERVER]\n";
    stream << "NAME=" << config.name << "\n";
    stream << "DESCRIPTION=" << config.description << "\n";
    stream << "PASSWORD=" << config.password << "\n";
    stream << "ADMIN_PASSWORD=" << config.adminPassword << "\n";
    stream << "IP=" << config.ip << "\n";
    stream << "PORT=" << config.port << "\n";
    stream << "HTTP_PORT=" << config.httpPort << "\n";
    stream << "MAX_CLIENTS=" << config.maxClients << "\n";
    stream << "SLOT_COUNT=" << config.slotCount << "\n\n";

    stream << "[TRACK]\n";
    stream << "TRACK=" << config.track << "\n";
    stream << "CONFIG_TRACK=" << config.trackConfig << "\n";
    stream << "DYNAMIC_TRACK=" << (config.dynamicTrack ? "1" : "0") << "\n";
    stream << "TRACK_CONDITIONS=" << config.trackConditions << "\n";
    stream << "GRIP=" << QString::number(config.gripModifier, 'f', 2) << "\n\n";

    stream << "[SESSION]\n";
    stream << "SESSION_TYPE=" << config.sessionType << "\n";
    stream << "SESSION_DURATION=" << config.sessionDuration << "\n";
    stream << "LAPS_COUNT=" << config.lapsCount << "\n";
    stream << "WAIT_TIME=" << config.waitTime << "\n\n";

    stream << "[WEATHER]\n";
    stream << "WEATHER=" << config.weather << "\n";
    stream << "TIME_OF_DAY=" << QString::number(config.timeOfDay, 'f', 2) << "\n";
    stream << "SUN_ANGLE=" << QString::number(config.sunAngle, 'f', 2) << "\n";
    stream << "USE_REAL_WEATHER=" << (config.useRealWeather ? "1" : "0") << "\n";
    stream << "TIME_MULTIPLIER=" << config.timeMultiplier << "\n\n";

    stream << "[RULES]\n";
    stream << "IS_LOCKED=" << (config.isLocked ? "1" : "0") << "\n";
    stream << "ALLOW_AUTOPILOT=" << (config.allowAutopilot ? "1" : "0") << "\n";
    stream << "ALLOW_VIRTUAL_MIRROR=" << (config.allowVirtualMirror ? "1" : "0") << "\n";
    stream << "MAX_BALLAST=" << config.maxBallast << "\n";
    stream << "DUMP_INTERVAL=" << config.dumpInterval << "\n";

    file.close();
    return true;
}

