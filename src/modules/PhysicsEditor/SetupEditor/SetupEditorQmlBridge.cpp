QVariantMap SetupEditorQmlBridge::importTelemetryLap(const QVariantMap& lapData) {
    TelemetryLapForSetup lap;
    lap.lapNumber = lapData.value("lapNumber").toInt();
    lap.lapTime = lapData.value("lapTime").toDouble();
    lap.sector1 = lapData.value("sector1").toDouble();
    lap.sector2 = lapData.value("sector2").toDouble();
    lap.sector3 = lapData.value("sector3").toDouble();
    lap.topSpeed = static_cast<float>(lapData.value("topSpeed").toDouble());
    lap.avgSpeed = static_cast<float>(lapData.value("avgSpeed").toDouble());
    lap.maxGForce = static_cast<float>(lapData.value("maxGForce").toDouble());

    // Import samples if present
    QVariantList samples = lapData.value("samples").toList();
    int throttleOn = 0, brakeOn = 0, coast = 0;
    int total = samples.size();

    for (const auto& s : samples) {
        QVariantMap sm = s.toMap();
        TelemetryDrivingSample sample;
        sample.speed = static_cast<float>(sm.value("speed").toDouble());
        sample.throttle = static_cast<float>(sm.value("throttle").toDouble());
        sample.brake = static_cast<float>(sm.value("brake").toDouble());
        sample.steering = static_cast<float>(sm.value("steering").toDouble());
        sample.lateralG = static_cast<float>(sm.value("latG").toDouble());
        sample.longitudinalG = static_cast<float>(sm.value("lonG").toDouble());
        lap.samples.append(sample);

        if (sample.throttle > 0.05f) throttleOn++;
        else if (sample.brake > 0.05f) brakeOn++;
        else coast++;
    }

    if (total > 0) {
        lap.throttleTimePercent = 100.0f * throttleOn / total;
        lap.brakeTimePercent = 100.0f * brakeOn / total;
        lap.coastTimePercent = 100.0f * coast / total;
    }

    m_importedLaps.append(lap);
    emit telemetryOptimizationReady(QVariantMap{{"imported", lap.lapNumber}, {"lapTime", lap.lapTime}});
    return {{"lapNumber", lap.lapNumber}, {"throttlePercent", lap.throttleTimePercent},
            {"brakePercent", lap.brakeTimePercent}, {"coastPercent", lap.coastTimePercent}};
}

QVariantList SetupEditorQmlBridge::analyzeDrivingStyle() {
    QVariantList insights;

    if (m_importedLaps.isEmpty()) {
        emit errorMessage("No telemetry laps imported");
        return insights;
    }

    // Find the best lap
    const TelemetryLapForSetup* bestLap = nullptr;
    for (const auto& lap : m_importedLaps) {
        if (!bestLap || lap.lapTime < bestLap->lapTime) bestLap = &lap;
    }
    if (!bestLap) return insights;

    // Analyze driving style from best lap
    float avgSteering = 0;
    int steeringSamples = 0;
    float maxSteeringSpeed = 0;
    float lateBrakingScore = 0;
    int brakeEvents = 0;

    for (size_t i = 1; i < bestLap->samples.size(); ++i) {
        const auto& prev = bestLap->samples[i - 1];
        const auto& cur = bestLap->samples[i];

        avgSteering += std::abs(cur.steering);
        steeringSamples++;

        // Detect steering at high speed
        if (cur.speed > 100 && std::abs(cur.steering) > 0.3f) {
            maxSteeringSpeed = std::max(maxSteeringSpeed, cur.speed);
        }

        // Detect late braking
        if (cur.brake > 0.3f && prev.brake < 0.1f) {
            brakeEvents++;
        }
    }

    if (steeringSamples > 0) avgSteering /= steeringSamples;

    // Generate insights
    QVariantMap style;
    if (avgSteering > 0.25f) {
        style["type"] = "aggressive_steering";
        style["message"] = "Aggressive steering input detected";
        style["suggestion"] = "Increase front ARB stiffness or reduce front camber";
        insights.append(style);
    }

    if (bestLap->throttleTimePercent > 70) {
        QVariantMap t;
        t["type"] = "early_throttle";
        t["message"] = QString("Heavy on throttle (%1% of lap)").arg(bestLap->throttleTimePercent, 0, 'f', 1);
        t["suggestion"] = "Consider softer rear springs for better traction on exit";
        insights.append(t);
    }

    if (bestLap->brakeTimePercent > 25) {
        QVariantMap b;
        b["type"] = "heavy_braking";
        b["message"] = QString("Brake-heavy driving style (%1% of lap)").arg(bestLap->brakeTimePercent, 0, 'f', 1);
        b["suggestion"] = "Increase brake torque or move bias rearward for better rotation";
        insights.append(b);
    }

    if (maxSteeringSpeed > 150) {
        QVariantMap s;
        s["type"] = "high_speed_correction";
        s["message"] = QString("Steering corrections at %1 km/h").arg(maxSteeringSpeed, 0, 'f', 0);
        s["suggestion"] = "Increase rear wing angle or reduce rear ride height";
        insights.append(s);
    }

    if (bestLap->maxGForce > 1.5f) {
        QVariantMap g;
        g["type"] = "high_grip";
        g["message"] = QString("High lateral load (%1 G)").arg(bestLap->maxGForce, 0, 'f', 2);
        g["suggestion"] = "Stiffen anti-roll bars and increase tire pressure";
        insights.append(g);
    }

    emit drivingAnalysisComplete(insights);
    return insights;
}

QVariantMap SetupEditorQmlBridge::autoOptimizeSetup() {
    if (m_importedLaps.isEmpty()) {
        emit errorMessage("No telemetry data for optimization");
        return {};
    }

    const TelemetryLapForSetup* bestLap = nullptr;
    for (const auto& lap : m_importedLaps) {
        if (!bestLap || lap.lapTime < bestLap->lapTime) bestLap = &lap;
    }
    if (!bestLap) return {};

    QVariantMap changes;
    QStringList recommendations;

    // Optimize based on driving style and telemetry
    float avgThrottle = 0, avgBrake = 0, avgSteering = 0;
    int count = bestLap->samples.size();
    for (const auto& s : bestLap->samples) {
        avgThrottle += s.throttle;
        avgBrake += s.brake;
        avgSteering += std::abs(s.steering);
    }
    if (count > 0) {
        avgThrottle /= count;
        avgBrake /= count;
        avgSteering /= count;
    }

    // Adjust differential based on throttle behavior
    if (avgThrottle > 0.3f) {
        QString currentDiff = m_currentSetup.value("DIFFERENTIAL.DRIVE_POWER", "0.5").toString();
        float diffVal = currentDiff.toFloat();
        if (avgSteering > 0.2f) {
            changes["DIFFERENTIAL.DRIVE_POWER"] = QString::number(std::min(diffVal + 0.1f, 1.0f), 'f', 4);
            recommendations.append("Increased power diff lock for better traction under throttle");
        } else {
            changes["DIFFERENTIAL.DRIVE_POWER"] = QString::number(std::max(diffVal - 0.1f, 0.2f), 'f', 4);
            recommendations.append("Reduced power diff lock for better corner entry");
        }
    }

    // Adjust brake bias based on braking behavior
    if (bestLap->brakeTimePercent > 20) {
        QString currentBias = m_currentSetup.value("BRAKES.FRONT_BIAS", "56").toString();
        float bias = currentBias.toFloat();
        if (avgBrake > 0.4f) {
            changes["BRAKES.FRONT_BIAS"] = QString::number(std::min(bias + 2.0f, 65.0f), 'f', 2);
            recommendations.append("Moved brake bias forward for more stable braking");
        }
    }

    // Adjust tire pressure based on lateral loads
    if (bestLap->maxGForce > 1.4f) {
        QString currentFront = m_currentSetup.value("TYRES.FRONT_PRESSURE_L", "26").toString();
        QString currentRear = m_currentSetup.value("TYRES.REAR_PRESSURE_L", "24").toString();
        changes["TYRES.FRONT_PRESSURE_L"] = QString::number(std::min(currentFront.toFloat() + 1.0f, 35.0f), 'f', 2);
        changes["TYRES.FRONT_PRESSURE_R"] = changes["TYRES.FRONT_PRESSURE_L"];
        changes["TYRES.REAR_PRESSURE_L"] = QString::number(std::min(currentRear.toFloat() + 1.0f, 35.0f), 'f', 2);
        changes["TYRES.REAR_PRESSURE_R"] = changes["TYRES.REAR_PRESSURE_L"];
        recommendations.append("Increased tire pressure for high lateral loads");
    }

    // Adjust final ratio based on top speed usage
    if (bestLap->topSpeed > 250) {
        QString currentRatio = m_currentSetup.value("BASIC.FINAL_RATIO", "3.50").toString();
        float ratio = currentRatio.toFloat();
        changes["BASIC.FINAL_RATIO"] = QString::number(std::max(ratio - 0.2, 2.5), 'f', 2);
        recommendations.append("Lengthened final ratio for higher top speed");
    } else if (bestLap->topSpeed < 180) {
        QString currentRatio = m_currentSetup.value("BASIC.FINAL_RATIO", "3.50").toString();
        float ratio = currentRatio.toFloat();
        changes["BASIC.FINAL_RATIO"] = QString::number(std::min(ratio + 0.3, 6.0), 'f', 2);
        recommendations.append("Shortened final ratio for better acceleration");
    }

    QVariantMap result;
    result["changes"] = changes;
    result["recommendations"] = QVariant::fromValue(recommendations);
    result["basedOnLap"] = bestLap->lapNumber;

    emit telemetryOptimizationReady(result);
    emit statusMessage(QString("Setup optimized based on lap %1 (%2 changes)")
                       .arg(bestLap->lapNumber).arg(changes.size()));

    // Apply the changes
    for (auto it = changes.begin(); it != changes.end(); ++it) {
        m_currentSetup[it.key()] = it.value();
    }
    m_isModified = true;

    return result;
}

QVariantMap SetupEditorQmlBridge::getTelemetryAnalysis() const {
    QVariantMap summary;
    summary["importedLaps"] = m_importedLaps.size();
    if (!m_importedLaps.isEmpty()) {
        const auto* bestLap = &m_importedLaps[0];
        for (const auto& lap : m_importedLaps) {
            if (lap.lapTime > 0 && lap.lapTime < bestLap->lapTime) {
                bestLap = &lap;
            }
        }
        summary["bestLapTime"] = bestLap->lapTime;
        summary["bestLapNumber"] = bestLap->lapNumber;
        summary["avgThrottlePercent"] = bestLap->throttleTimePercent;
        summary["avgBrakePercent"] = bestLap->brakeTimePercent;
        summary["avgCoastPercent"] = bestLap->coastTimePercent;
        summary["maxGForce"] = bestLap->maxGForce;
        summary["topSpeed"] = bestLap->topSpeed;
    }
    return summary;
}

