void SetupEditorQmlBridge::loadSetup(const QString& path) {
    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        emit errorMessage("Cannot open setup: " + path);
        return;
    }

    m_currentSetupPath = path;
    m_currentSetup.clear();
    m_isModified = false;

    QTextStream in(&file);
    QString currentSection;
    while (!in.atEnd()) {
        QString line = in.readLine().trimmed();
        if (line.isEmpty() || line.startsWith(";")) continue;

        if (line.startsWith("[") && line.endsWith("]")) {
            currentSection = line.mid(1, line.length() - 2);
            continue;
        }

        int eqIdx = line.indexOf("=");
        if (eqIdx > 0) {
            QString key = line.left(eqIdx).trimmed();
            QString value = line.mid(eqIdx + 1).trimmed();
            m_currentSetup[currentSection + "." + key] = value;
        }
    }

    file.close();
    emit statusMessage("Loaded setup: " + QFileInfo(path).fileName());
    emit setupLoaded();
}

void SetupEditorQmlBridge::saveSetup(const QString& path) {
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        emit errorMessage("Cannot save setup: " + path);
        return;
    }

    QTextStream out(&file);
    out << "; ksEditor Setup Export\n";
    out << "; Generated by ksEditor\n\n";

    QString currentSection;
    for (auto it = m_currentSetup.constBegin(); it != m_currentSetup.constEnd(); ++it) {
        QString key = it.key();
        QString value = it.value().toString();

        if (key.contains(".")) {
            QString section = key.section(".", 0, 0);
            QString subKey = key.section(".", 1);
            if (section != currentSection) {
                if (!currentSection.isEmpty()) out << "\n";
                out << "[" << section << "]\n";
                currentSection = section;
            }
            out << subKey << "=" << value << "\n";
        } else {
            out << key << "=" << value << "\n";
        }
    }

    file.close();
    m_currentSetupPath = path;
    m_isModified = false;
    emit statusMessage("Saved setup: " + QFileInfo(path).fileName());
    emit setupApplied();
}

void SetupEditorQmlBridge::analyzeSetup() {
    if (m_currentSetup.isEmpty()) {
        emit errorMessage("No setup loaded for analysis");
        return;
    }

    // Analyze key parameters and provide recommendations
    QStringList recommendations;

    if (m_currentSetup.contains("BASIC.WEIGHT")) {
        float weight = m_currentSetup["BASIC.WEIGHT"].toFloat();
        if (weight > 1500) recommendations.append("Car is heavy - consider softer springs");
        if (weight < 800) recommendations.append("Car is light - consider stiffer springs");
    }

    if (m_currentSetup.contains("FRONT.SPRING_RATE") && m_currentSetup.contains("REAR.SPRING_RATE")) {
        float front = m_currentSetup["FRONT.SPRING_RATE"].toFloat();
        float rear = m_currentSetup["REAR.SPRING_RATE"].toFloat();
        if (front > rear * 1.3f)
            recommendations.append("Front springs much stiffer than rear - may cause oversteer");
        if (rear > front * 1.3f)
            recommendations.append("Rear springs much stiffer than front - may cause understeer");
    }

    if (m_currentSetup.contains("FRONT.CAMBER") && m_currentSetup.contains("REAR.CAMBER")) {
        float frontCamber = m_currentSetup["FRONT.CAMBER"].toFloat();
        float rearCamber = m_currentSetup["REAR.CAMBER"].toFloat();
        if (std::abs(frontCamber) > 3.5f)
            recommendations.append("Front camber exceeds 3.5 degrees - excessive tire wear expected");
        if (std::abs(rearCamber) > 3.0f)
            recommendations.append("Rear camber exceeds 3.0 degrees - excessive tire wear expected");
    }

    if (m_currentSetup.contains("BASIC.FINAL_RATIO")) {
        float finalRatio = m_currentSetup["BASIC.FINAL_RATIO"].toFloat();
        if (finalRatio > 5.0f) recommendations.append("Very short final ratio - high acceleration, low top speed");
        if (finalRatio < 2.5f) recommendations.append("Very long final ratio - high top speed, low acceleration");
    }

    emit setupAnalysisComplete(recommendations);
    emit statusMessage(QString("Setup analysis complete: %1 recommendations").arg(recommendations.size()));
}

void SetupEditorQmlBridge::compareWith(const QString& otherPath) {
    QVariantMap otherSetup;
    QFile file(otherPath);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        emit errorMessage("Cannot open setup for comparison: " + otherPath);
        return;
    }

    QTextStream in(&file);
    QString currentSection;
    while (!in.atEnd()) {
        QString line = in.readLine().trimmed();
        if (line.isEmpty() || line.startsWith(";")) continue;
        if (line.startsWith("[") && line.endsWith("]")) {
            currentSection = line.mid(1, line.length() - 2);
            continue;
        }
        int eqIdx = line.indexOf("=");
        if (eqIdx > 0) {
            otherSetup[currentSection + "." + line.left(eqIdx).trimmed()] = line.mid(eqIdx + 1).trimmed();
        }
    }
    file.close();

    // Find differences
    QStringList diffs;
    QSet<QString> allKeys;
    for (auto it = m_currentSetup.begin(); it != m_currentSetup.end(); ++it) allKeys.insert(it.key());
    for (auto it = otherSetup.begin(); it != otherSetup.end(); ++it) allKeys.insert(it.key());

    for (const QString& key : allKeys) {
        QString currentVal = m_currentSetup.value(key).toString();
        QString otherVal = otherSetup.value(key).toString();
        if (currentVal != otherVal) {
            diffs.append(QString("%1: %2 -> %3").arg(key).arg(otherVal, currentVal));
        }
    }

    emit comparisonComplete(diffs);
    if (diffs.isEmpty()) {
        emit statusMessage("Setups are identical");
    } else {
        emit statusMessage(QString("Found %1 differences between setups").arg(diffs.size()));
    }
}

