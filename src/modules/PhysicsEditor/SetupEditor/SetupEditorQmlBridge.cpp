QStringList SetupEditorQmlBridge::getRecentSetups() const {
    QStringList setups;
    QDir dir(m_setupDir);
    if (dir.exists()) {
        QStringList entries = dir.entryList({"*.ini"}, QDir::Files, QDir::Time);
        for (int i = 0; i < std::min<qsizetype>(entries.size(), 20); ++i) {
            setups.append(dir.absoluteFilePath(entries[i]));
        }
    }
    return setups;
}

void SetupEditorQmlBridge::exportToCar(const QString& carName, const QString& trackName) {
    if (m_currentSetup.isEmpty()) {
        emit errorMessage("No setup to export");
        return;
    }

    QString exportPath = m_setupDir + "/" + carName + "/" + trackName;
    QDir().mkpath(exportPath);
    saveSetup(exportPath + "/setup.ini");
    emit statusMessage("Exported setup for " + carName + " at " + trackName);
}

QStringList SetupEditorQmlBridge::getSetupKeys() const {
    QStringList keys;
    QSet<QString> sections;
    for (auto it = m_currentSetup.begin(); it != m_currentSetup.end(); ++it) {
        if (it.key().contains(".")) {
            sections.insert(it.key().section(".", 0, 0));
        }
    }
    return sections.values();
}

